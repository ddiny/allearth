(() => {
  "use strict";
  const channel = "allearth-prototype";
  const from = new URLSearchParams(location.search).get("from") === "b" ? "b" : "a";
  const form = document.querySelector(".signup-form");
  const handle = document.getElementById("handle");
  const nickname = document.getElementById("nickname");
  const all = document.getElementById("consent-all");
  const required = [...document.querySelectorAll(".required-consent")];
  const submit = document.querySelector(".signup-submit");
  const dialog = document.getElementById("privacy-dialog");
  let composing = false;
  let submitting = false;
  let lastFocus = null;
  const touched = new Set();

  function publish(action, detail = {}) {
    const event = { channel, screen: "signup", action, timestamp: Date.now(), detail: { mode: "preview", ...detail } };
    window.dispatchEvent(new CustomEvent("allearth:action", { detail: event }));
    if (window.parent !== window) window.parent.postMessage(event, location.protocol === "file:" ? "*" : location.origin);
  }
  function chars(value) {
    if (window.Intl && Intl.Segmenter) return [...new Intl.Segmenter("ko", { granularity: "grapheme" }).segment(value)].length;
    return [...value].length;
  }
  function validHandle() { return handle.value === "" || /^[a-z0-9_]{4,16}$/.test(handle.value); }
  function validNickname() { return !window.AllEarthStore.nicknameError(nickname.value); }
  function setError(input, message) {
    const error = document.getElementById(`${input.id}-error`);
    input.setAttribute("aria-invalid", String(Boolean(message)));
    error.textContent = message;
  }
  function showValidation(input) {
    if (composing || !touched.has(input.id)) return;
    if (input === handle) setError(input, validHandle() ? "" : "사용자명은 영문 소문자, 숫자, _로 4~16자 입력해 주세요.");
    if (input === nickname) setError(input, window.AllEarthStore.nicknameError(nickname.value));
  }
  function syncAll() {
    const count = required.filter(input => input.checked).length;
    all.checked = count === required.length;
    all.indeterminate = count > 0 && count < required.length;
  }
  function updateSubmit() { submit.disabled = composing || submitting || !validHandle() || !validNickname() || !required.every(input => input.checked); }
  [handle, nickname].forEach(input => {
    input.addEventListener("compositionstart", () => { composing = true; updateSubmit(); });
    input.addEventListener("compositionend", () => { composing = false; showValidation(input); updateSubmit(); });
    input.addEventListener("blur", () => { touched.add(input.id); showValidation(input); updateSubmit(); });
    input.addEventListener("input", () => { if (!composing) showValidation(input); updateSubmit(); });
  });
  all.addEventListener("change", () => { required.forEach(input => { input.checked = all.checked; }); all.indeterminate = false; updateSubmit(); });
  required.forEach(input => input.addEventListener("change", () => { syncAll(); updateSubmit(); }));
  document.addEventListener("click", event => {
    const button = event.target.closest("button[data-action]");
    if (!button) return;
    if (button.dataset.action === "privacy") {
      event.preventDefault();
      lastFocus = button;
      publish("legal.requested", { document: "privacy", available: false });
      dialog.showModal();
    }
    if (button.dataset.action === "close-dialog") dialog.close();
    if (button.dataset.action === "close") {
      publish("signup.cancelled", { from });
      location.href = from === "b" ? "index-b.html" : "index.html";
    }
  });
  dialog.addEventListener("close", () => { if (lastFocus) lastFocus.focus(); });
  form.addEventListener("submit", event => {
    event.preventDefault();
    [handle, nickname].forEach(input => { touched.add(input.id); showValidation(input); });
    updateSubmit();
    if (submit.disabled || submitting || composing) return;
    submitting = true;
    updateSubmit();
    submit.setAttribute("aria-busy", "true");
    submit.textContent = "가입 중";
    window.setTimeout(() => {
      window.AllEarthStore.rename(nickname.value);
      window.AllEarthStore.login();
      publish("signup.completed", { autoGeneratedHandle: handle.value === "" });
      location.href = `complete.html?kind=new&from=${from}`;
    }, 500);
  });
  document.fonts.ready.then(() => publish("screen.ready", { from }));
})();
